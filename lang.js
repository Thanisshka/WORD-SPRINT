let currentLanguage = 'ta';

function toggleLanguage() {
    currentLanguage = (currentLanguage === 'ta') ? 'en' : 'ta';
    applyTranslations();
    
    const kuralEn = document.getElementById('kural-english-meaning');
    if (kuralEn) {
        if (currentLanguage === 'en') {
            kuralEn.classList.remove('hidden');
        } else {
            kuralEn.classList.add('hidden');
        }
    }

    if(document.getElementById('quiz-result') && !document.getElementById('quiz-result').classList.contains('hidden')) {
        updateQuizSummaryText();
    }
}

function applyTranslations() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLanguage][key]) {
            el.innerHTML = translations[currentLanguage][key];
        }
    });
}

function updateQuizSummaryText() {
    const total = 3;
    const score = window.persistenceScore || 0;
    const percentage = (score / total) * 100;
    const summaryEl = document.getElementById('quiz-summary');
    const msgEl = document.getElementById('quiz-message');
    
    if(currentLanguage === 'en') {
        summaryEl.textContent = `You chose persistence in ${score} out of ${total} situations.`;
        if (percentage >= 80) msgEl.textContent = "Keep that spirit. Obstacles don't define the journey.";
        else if (percentage >= 60) msgEl.textContent = "You know the value of persistence. Keep building it.";
        else if (percentage >= 40) msgEl.textContent = "Every journey gives you another chance to continue.";
        else msgEl.textContent = "Remember: failure is not the opposite of success. It can be part of the path.";
    } else {
        summaryEl.textContent = `${total}-ல் ${score} சூழ்நிலைகளில் விடாமுயற்சியைத் தேர்ந்தெடுத்துள்ளீர்கள்.`;
        if (percentage >= 80) msgEl.textContent = "இதே மனப்பான்மையைத் தொடருங்கள். தடைகள் உங்களைத் தீர்மானிப்பதில்லை.";
        else if (percentage >= 60) msgEl.textContent = "உங்களுக்கு விடாமுயற்சியின் மதிப்பு தெரியும். அதை தொடர்ந்து வளர்த்துக்கொள்ளுங்கள்.";
        else if (percentage >= 40) msgEl.textContent = "ஒவ்வொரு பயணமும் தொடர இன்னொரு வாய்ப்பைத் தருகிறது.";
        else msgEl.textContent = "நினைவில் கொள்க: தோல்வி வெற்றியின் எதிர்ப்பதம் அல்ல. அது பயணத்தின் ஒரு பகுதி.";
    }
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
});
